/// Very simple keyword-overlap scoring — no ML, no network call. Picks
/// whichever knowledge-base entry shares the most keywords with the
/// user's message, falling back to a generic helpful response.
String findBestResponse(String userMessage) {
  final normalized = userMessage.trim();
  if (normalized.isEmpty) return _fallbackResponse;

  _KnowledgeEntry? best;
  int bestScore = 0;

  for (final entry in _knowledgeBase) {
    var score = 0;
    for (final keyword in entry.keywords) {
      if (normalized.contains(keyword)) score++;
    }
    if (score > bestScore) {
      bestScore = score;
      best = entry;
    }
  }

  return best?.response ?? _fallbackResponse;
}
